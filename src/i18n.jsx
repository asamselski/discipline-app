const interpolate = (text, params = {}) => Object.entries(params).reduce(
  (result, [key, value]) => result.replaceAll(`{{${key}}}`, String(value)),
  text,
);

const translateEnglish = (key) => {
  if (EN[key]) return EN[key];

  let match = key.match(/^Przekroczono czas ładowania biblioteki (.+)\.$/);
  if (match) return `Loading the ${match[1]} library timed out.`;
  match = key.match(/^Nie udało się pobrać biblioteki (.+)\.$/);
  if (match) return `The ${match[1]} library could not be downloaded.`;
  match = key.match(/^Błąd usługi powiadomień \((\d+)\)\.$/);
  if (match) return `Notification service error (${match[1]}).`;

  return key;
};

export function I18nProvider({ children }) {
  const [language, setLanguageState] = useState(() => localStorage.getItem('discipline_language') === 'en' ? 'en' : 'pl');
  const setLanguage = (nextLanguage) => setLanguageState(nextLanguage === 'en' ? 'en' : 'pl');

  useEffect(() => {
    localStorage.setItem('discipline_language', language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({
    language,
    locale: language === 'en' ? 'en-GB' : 'pl-PL',
    setLanguage,
    t: (key, params) => interpolate(language === 'en' ? translateEnglish(key) : key, params),
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

